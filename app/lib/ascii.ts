/** Renders text as 6 rows of block letters. */
export function bannerRows(text: string) {
  return Array.from({ length: 6 }, (_, row) =>
    [...text.toUpperCase()].map((ch) => GLYPHS[ch]?.[row] ?? "").join(""),
  );
}

/** Renders text as one 6-line block-letter string. */
export function banner(text: string) {
  return bannerRows(text).join("\n");
}
